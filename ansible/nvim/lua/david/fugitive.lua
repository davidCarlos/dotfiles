function DiffNameOnly(target)
	print(target)
	local diff_target = string.format("%s...HEAD", target)
	local diff_cmd = string.format("Git difftool --name-status %s", diff_target)
	vim.cmd(diff_cmd)
end

vim.keymap.set("n", "<leader>dn", ":lua DiffNameOnly('")
vim.keymap.set("n", "<leader>gd", ":Gvdiffsplit ")
vim.keymap.set("n", "<leader>gw", ":Gwrite<cr>")
vim.keymap.set("n", "<leader>g", ":Git ")
vim.keymap.set("n", "<leader>gs", ":10split|0Git<cr>")
vim.keymap.set("n", "<leader>gc", ":10split|0Git commit<cr>")
vim.keymap.set("n", "<leader>gpl", ":Git pull ")
vim.keymap.set("n", "gik", ":Git checkout %<cr>")
vim.keymap.set("n", "gp", ":Git push origin")
vim.keymap.set("n", "<leader>gl", ":vertical Git log<cr>")
